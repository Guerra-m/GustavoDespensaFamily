-- Promos por porcentaje: distintas de Promocion (combo "lleva x, paga y",
-- solo UNIDAD). Un Descuento resta un % al precio y aplica a cualquier
-- tipoCantidad, y puede apuntar a un producto puntual o a toda una
-- categoria (alcance).
create table if not exists descuento (
    id bigint generated by default as identity primary key,
    alcance varchar(20) not null,
    producto_id bigint,
    categoria_id bigint,
    porcentaje double precision not null,
    activo boolean not null default true,
    constraint fk_descuento_producto foreign key (producto_id) references producto(id),
    constraint fk_descuento_categoria foreign key (categoria_id) references categoria(id)
);
