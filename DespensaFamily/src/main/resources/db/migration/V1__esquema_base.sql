-- Punto de partida de las migraciones: el esquema completo, tal como lo genera
-- Hibernate a partir de las entidades al 01/09/2026.
--
-- Este archivo es idempotente a proposito (IF NOT EXISTS en todo). No es un
-- adorno: cuando Flyway entra en un proyecto que ya venia con ddl-auto=update,
-- las bases que andan dando vueltas no estan todas en el mismo estado. Hay tres
-- que existen de verdad:
--
--   1. Una base nueva, vacia.
--   2. La base de Martin: todo lo del 01/09 aplicado menos
--      usuario.debe_cambiar_password, que es donde Hibernate se corto.
--   3. Cualquier copia anterior al 01/09 (un respaldo, una instalacion vieja).
--
-- V1 lleva las tres al mismo lugar. Por eso primero crea lo que falte y despues
-- agrega columna por columna: correrlo sobre una base ya completa no hace nada.
--
-- A partir de aca, CADA cambio de esquema es un V2, V3... nuevo. Nunca se edita
-- una migracion ya aplicada: Flyway guarda su checksum y se niega a arrancar si
-- cambio, que es exactamente la red que faltaba.

-- ---------------------------------------------------------------- tablas

create table if not exists categoria (id bigint generated by default as identity, descripcion varchar(255), nombre varchar(255), primary key (id));
create table if not exists compra (fecha_anulacion timestamp(6), fecha_hora timestamp(6), id bigint generated by default as identity, anulada_por varchar(255), proveedor varchar(255), usuario varchar(255), estado enum ('ACTIVA','ANULADA'), primary key (id));
create table if not exists configuracion (ganancia_por_defecto float(53), umbral_stock_bajo float(53), id bigint not null, version bigint, nombre_negocio varchar(255), primary key (id));
create table if not exists detalle_compra (cantidad float(53) not null, precio_costo float(53) not null, precio_costo_anterior float(53), subtotal float(53) not null, compra_id bigint, id bigint generated by default as identity, producto_id bigint, primary key (id));
create table if not exists detalle_venta (cantidad float(53) not null, precio_costo float(53) not null, precio_unitario float(53) not null, subtotal float(53) not null, id bigint generated by default as identity, producto_id bigint, venta_id bigint, primary key (id));
create table if not exists producto (activo boolean not null, fraccion_minima float(53), porcentaje_ganancia float(53) not null, precio_costo float(53) not null, precio_venta float(53) not null, stock float(53) not null, unidades_por_paquete integer, categoria_id bigint, id bigint generated by default as identity, version bigint, codigo_barras varchar(255), imagen_url varchar(255), nombre varchar(255), proveedor varchar(255), tipo_cantidad varchar(255), unidad_medida varchar(255), primary key (id));
create table if not exists promocion (activo boolean not null, cantidad_lleva integer not null, cantidad_paga integer not null, id bigint generated by default as identity, producto_id bigint, primary key (id));
create table if not exists usuario (debe_cambiar_password boolean default false not null, id bigint generated by default as identity, nombre varchar(255), password varchar(255), rol varchar(255), username varchar(255) unique, primary key (id));
create table if not exists venta (total float(53) not null, fecha_anulacion timestamp(6), fecha_hora timestamp(6), id bigint generated by default as identity, anulada_por varchar(255), usuario varchar(255), estado enum ('ACTIVA','ANULADA') default 'ACTIVA' not null, primary key (id));

-- ------------------------------------------------- columnas de la tanda 01/09
-- Sobre una base que ya las tiene, cada linea es un no-op.

-- La que dejaba la aplicacion sin arrancar. El DEFAULT no es cosmetico: es lo
-- unico que permite agregar una columna NOT NULL a una tabla que ya tiene
-- usuarios adentro. Y false es la respuesta correcta: al dueno que ya eligio su
-- password no hay que pedirle que la cambie porque actualizamos el sistema.
alter table usuario add column if not exists debe_cambiar_password boolean default false not null;

-- Quien vendio y quien anulo. Una venta vieja se hizo: ACTIVA, sin anulador.
alter table venta add column if not exists usuario varchar(255);
alter table venta add column if not exists anulada_por varchar(255);
alter table venta add column if not exists fecha_anulacion timestamp(6);
alter table venta add column if not exists estado enum ('ACTIVA','ANULADA') default 'ACTIVA' not null;

alter table compra add column if not exists usuario varchar(255);
alter table compra add column if not exists anulada_por varchar(255);
alter table compra add column if not exists fecha_anulacion timestamp(6);
alter table compra add column if not exists estado enum ('ACTIVA','ANULADA') default 'ACTIVA';

-- Lo que permite anular una compra devolviendo el costo previo. En las compras
-- anteriores no hay a que volver: queda null, y anularlas va a fallar con un
-- mensaje claro en vez de inventar un precio.
alter table detalle_compra add column if not exists precio_costo_anterior float(53);

-- fecha_hora siempre se llamo asi pero guardaba solo el dia. Los reportes por
-- rango y el agrupado por dia dependen de que sea timestamp.
alter table venta alter column fecha_hora timestamp(6);
alter table compra alter column fecha_hora timestamp(6);

