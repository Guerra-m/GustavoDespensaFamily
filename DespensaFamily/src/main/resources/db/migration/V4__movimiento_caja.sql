-- El libro de movimientos: la unica fuente de verdad sobre el dinero.
--
-- Los enums quedan como varchar y no como el tipo ENUM nativo de H2 que usan
-- estado_venta/estado_compra. Es a proposito: un ENUM nativo obliga a ALTER
-- TABLE cada vez que se agrega un valor (va a pasar pronto: SUELDO, cuando se
-- construya la etapa de empleados). varchar no.
--
-- Sin foreign keys hacia venta/compra: son referencias sueltas, igual que
-- Venta.usuario es un varchar y no una relacion a Usuario (ver el comentario
-- en MovimientoCaja.java). El libro no depende de que esa venta o esa compra
-- sigan existiendo tal cual para poder señalar de donde salio un peso.

create table if not exists movimiento_caja (
    id bigint generated by default as identity,
    fecha_hora timestamp(6) not null,
    tipo varchar(20) not null,
    categoria varchar(20) not null,
    monto float(53) not null,
    metodo_pago varchar(20) not null,
    descripcion varchar(500),
    usuario varchar(255),
    venta_id bigint,
    compra_id bigint,
    revierte_a bigint,
    primary key (id)
);

-- El saldo y los reportes siempre filtran por rango de fecha: sin este
-- indice, cada consulta de caja escanea la tabla entera a medida que crece.
create index if not exists idx_movimiento_caja_fecha on movimiento_caja(fecha_hora);

-- Para "cuanto se le debe pagar" en la etapa de empleados y para poder listar
-- los movimientos de una venta o compra puntual sin escanear todo.
create index if not exists idx_movimiento_caja_venta on movimiento_caja(venta_id);
create index if not exists idx_movimiento_caja_compra on movimiento_caja(compra_id);
