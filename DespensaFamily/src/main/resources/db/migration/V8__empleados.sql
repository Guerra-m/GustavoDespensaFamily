-- Empleados: quien cobra, y que dias trabajo. Alcance agregado despues del
-- mapa original (ver PLAN-INSTALADOR.md), no toca el camino de la venta —
-- entra sin rehacer nada de lo anterior.
--
-- empleado NO tiene columna username con foreign key: es una referencia
-- suelta, igual que Venta.usuario. Un empleado puede existir sin usar nunca
-- el sistema.

create table if not exists empleado (
    id bigint generated by default as identity,
    nombre varchar(255) not null,
    activo boolean default true not null,
    username varchar(255),
    primary key (id)
);

-- Una fila = un dia trabajado. Sin booleano: si la fila existe, trabajo.
create table if not exists dia_trabajado (
    id bigint generated by default as identity,
    empleado_id bigint not null,
    fecha date not null,
    primary key (id)
);

-- Un empleado no puede quedar marcado dos veces el mismo dia.
create unique index if not exists idx_dia_trabajado_unico on dia_trabajado(empleado_id, fecha);

create index if not exists idx_dia_trabajado_fecha on dia_trabajado(fecha);

alter table dia_trabajado add constraint if not exists fk_dia_trabajado_empleado
    foreign key (empleado_id) references empleado(id);

-- A que empleado se le pago, cuando el movimiento es categoria SUELDO. Suelta
-- y sin foreign key, mismo criterio que venta_id/compra_id en esta tabla.
alter table movimiento_caja add column if not exists empleado_id bigint;
create index if not exists idx_movimiento_caja_empleado on movimiento_caja(empleado_id);
