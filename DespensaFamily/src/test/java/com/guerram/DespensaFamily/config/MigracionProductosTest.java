package com.guerram.DespensaFamily.config;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * DF-DATA-001 y DF-BUG-009 contra una base con datos "sucios" reales: un
 * producto con tipo_cantidad nulo y stock ya en decimal (38,5), otro con
 * tipo nulo pero stock entero, uno ya coherente por peso, y uno dado de baja
 * con su propio codigo de barras.
 *
 * Mismo patron que MigracionBaseDeMartinTest: se siembra el esquema ANTES de
 * que exista Flyway y se deja correr la cadena completa de migraciones real
 * (hasta V13/V14 incluidas), asi se prueba el codigo de produccion y no una
 * copia.
 */
@SpringBootTest(properties = {
        "despensa.escritorio=false",
        "despensa.respaldos.al-arrancar=false",
        "spring.datasource.url=jdbc:h2:mem:productos-sucios;DB_CLOSE_DELAY=-1"
})
class MigracionProductosTest {

    static {
        EsquemaDePrueba.sembrar(
                "jdbc:h2:mem:productos-sucios;DB_CLOSE_DELAY=-1", "/db/productos-sucios.sql");
    }

    @Autowired
    private JdbcTemplate jdbc;

    @Test
    void completaElTipoNuloConUnidadSegunLaDecisionDelDueño() {
        assertThat(jdbc.queryForObject(
                "select tipo_cantidad from producto where id = 1", String.class))
                .isEqualTo("UNIDAD");
        assertThat(jdbc.queryForObject(
                "select tipo_cantidad from producto where id = 2", String.class))
                .isEqualTo("UNIDAD");
    }

    @Test
    void noQuedaNingunProductoConTipoNulo() {
        assertThat(jdbc.queryForObject("select count(*) from producto where tipo_cantidad is null", Integer.class))
                .isZero();
    }

    @Test
    void redondeaParaArribaElStockDecimalDeUnProductoPorUnidadSinPerderExistencias() {
        // 38,5 -> 39: nunca 38 (perderia media unidad real) ni se deja el
        // decimal (que ya no tendria sentido con tipo_cantidad NOT NULL).
        assertThat(jdbc.queryForObject("select stock from producto where id = 1", Double.class))
                .isEqualTo(39.0);
    }

    @Test
    void noTocaElStockDeUnProductoQueYaEraEnteroEnUnidad() {
        assertThat(jdbc.queryForObject("select stock from producto where id = 2", Double.class))
                .isEqualTo(12.0);
    }

    @Test
    void noTocaElStockDecimalDeUnProductoQueYaEraPorPeso() {
        assertThat(jdbc.queryForObject("select stock from producto where id = 3", Double.class))
                .isEqualTo(2.75);
        assertThat(jdbc.queryForObject("select tipo_cantidad from producto where id = 3", String.class))
                .isEqualTo("PESO");
    }

    @Test
    void normalizaCodigoDeBarrasVacioANulo() {
        assertThat(jdbc.queryForObject(
                "select codigo_barras from producto where id = 2", String.class))
                .isNull();
    }

    @Test
    void laColumnaTipoCantidadQuedaNotNull() {
        assertThatThrownBy(() -> jdbc.update(
                "insert into producto (id, activo, nombre, porcentaje_ganancia, precio_costo, precio_venta, stock, tipo_cantidad) "
                        + "values (997, true, 'Sin tipo a mano', 10.0, 1.0, 1.1, 1.0, null)"))
                .isInstanceOf(DataIntegrityViolationException.class);
    }

    @Test
    void elIndiceUnicoRechazaUnCodigoDeBarrasYaUsadoPorOtroProducto() {
        // El id 3 ya quedo con codigo '7791112223334'; intentar reusarlo
        // tiene que chocar con el indice de V14.
        assertThatThrownBy(() -> jdbc.update(
                "insert into producto (id, activo, nombre, porcentaje_ganancia, precio_costo, precio_venta, stock, tipo_cantidad, codigo_barras) "
                        + "values (998, true, 'Choca con el 3', 10.0, 1.0, 1.1, 1.0, 'UNIDAD', '7791112223334')"))
                .isInstanceOf(DataIntegrityViolationException.class);
    }

    @Test
    void elIndiceUnicoPermiteVariosProductosSinCodigoDeBarras() {
        // Dos NULL no chocan entre si -- es justamente lo que permite el
        // "normalizar vacio a NULL antes del indice" de V14.
        //
        // Id explicito (999): la fila 1-4 ya se sembro con id a mano en el
        // seed, y GENERATED BY DEFAULT AS IDENTITY no se entera de esos ids
        // manuales, asi que un insert sin id puede repetir uno ya usado.
        jdbc.update(
                "insert into producto (id, activo, nombre, porcentaje_ganancia, precio_costo, precio_venta, stock, tipo_cantidad) "
                        + "values (999, true, 'Sin codigo mas', 10.0, 1.0, 1.1, 1.0, 'UNIDAD')");

        assertThat(jdbc.queryForObject(
                "select count(*) from producto where codigo_barras is null", Integer.class))
                .isGreaterThanOrEqualTo(2);
    }

    @Test
    void unProductoDadoDeBajaSigueBloqueandoSuPropioCodigo() {
        // Decision tomada: el codigo de un producto inactivo (id 4) tambien
        // cuenta para la unicidad.
        assertThatThrownBy(() -> jdbc.update(
                "insert into producto (id, activo, nombre, porcentaje_ganancia, precio_costo, precio_venta, stock, tipo_cantidad, codigo_barras) "
                        + "values (996, true, 'Quiere el codigo del borrado', 10.0, 1.0, 1.1, 1.0, 'UNIDAD', '7795556667778')"))
                .isInstanceOf(DataIntegrityViolationException.class);
    }

    @Test
    void conservaLosDatosDelNegocio() {
        assertThat(jdbc.queryForObject("select nombre from producto where id = 3", String.class))
                .isEqualTo("Fiambre surtido");
        // >= y no ==: otros tests de esta clase insertan filas extra sobre
        // la misma base en memoria (comparten contexto de Spring); lo que
        // importa es que las 4 originales sigan estando, no el total.
        assertThat(jdbc.queryForObject("select count(*) from producto", Integer.class))
                .isGreaterThanOrEqualTo(4);
    }
}
